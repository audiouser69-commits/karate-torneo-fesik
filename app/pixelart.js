  // disegna la figura centrata nel canvas, scalata a numeri interi
  function render(canvas, key, frameIdx, opts) {
    opts = opts || {};
    const ctx = canvas.getContext('2d'); ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    if (key === 'custom' && opts.image) {
      const im = opts.image; const sc = Math.min(canvas.width / im.width, canvas.height / im.height);
      const w = im.width * sc, h = im.height * sc; ctx.drawImage(im, (canvas.width - w) / 2, (canvas.height - h) / 2, w, h); return;
    }
    const f = F[key]; if (!f) return;
    const fr = f.frames[(frameIdx || 0) % f.frames.length];
    // ritaglia righe/colonne vuote per centrare
    let minX = 99, maxX = -1, minY = 99, maxY = -1;
    fr.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] !== '.') { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); } });
    const w = maxX - minX + 1, h = maxY - minY + 1;
    const px = Math.max(1, Math.floor(Math.min(canvas.width / w, canvas.height / h)));
    const crop = fr.slice(minY, maxY + 1).map(r => r.slice(minX, maxX + 1));
    draw(ctx, crop, Math.floor((canvas.width - w * px) / 2), Math.floor((canvas.height - h * px) / 2), px);
  }
  const list = () => Object.keys(F).map(k => ({ key: k, label: F[k].label, frames: F[k].frames.length }));
  const api = { PAL, FIGURES: F, render, list, size };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.PixelArt = api;
